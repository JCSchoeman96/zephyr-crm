create function private.has_active_profile()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
	select exists (
		select 1
		from public.profiles
		where id = (select auth.uid())
		  and status = 'active'
	);
$$;

create function private.has_any_role(allowed_roles text[])
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
	select exists (
		select 1
		from public.profiles
		where id = (select auth.uid())
		  and status = 'active'
		  and role = any (allowed_roles)
	);
$$;

create function private.current_user_role()
returns text
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
	select role
	from public.profiles
	where id = (select auth.uid())
	  and status = 'active'
	limit 1;
$$;

