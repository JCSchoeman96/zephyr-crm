$$;

create function private.validate_lead_loss()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
declare
	lost_reason_code text;
begin
	if new.pipeline_stage = 'LOST' then
		select code into lost_reason_code
		from public.lost_reasons
		where id = new.lost_reason_id and active;
		if lost_reason_code is null then
			raise exception using errcode = '23514', message = 'LOST leads require an active lost reason';
		end if;
		if lost_reason_code = 'other' and length(trim(coalesce(new.lost_notes, ''))) = 0 then
			raise exception using errcode = '23514', message = 'The other lost reason requires lost_notes';
		end if;
	end if;
	return new;
end;
$$;

create function private.enforce_lock_version()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
	if new.lock_version <> old.lock_version + 1 then
		raise exception using
			errcode = '40001',
			message = format('stale or invalid lock_version for %s', tg_table_name);
	end if;
	return new;
end;
$$;

create function private.protect_profile_privileges()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
declare
	actor_role text;
begin
	if current_user in ('postgres', 'service_role', 'supabase_admin') then
		return new;
	end if;
	if new.id is distinct from old.id or new.email is distinct from old.email then
		raise exception using errcode = '42501', message = 'Profile identity fields are Auth-managed';
	end if;
	actor_role = private.current_user_role();
	if actor_role is null then
		raise exception using errcode = '42501', message = 'An active profile is required';
	end if;
	if actor_role <> 'owner' and (
		new.role is distinct from old.role or new.status is distinct from old.status
	) then
		raise exception using errcode = '42501', message = 'Only the owner may change profile role or status';
	end if;
	return new;
end;
$$;

create function private.protect_quote_immutability()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
	if old.status in ('sent', 'accepted', 'declined', 'expired', 'cancelled', 'superseded') and (
		new.lead_id is distinct from old.lead_id or
		new.client_id is distinct from old.client_id or
		new.currency is distinct from old.currency or
		new.subject is distinct from old.subject or
		new.introduction is distinct from old.introduction or
		new.terms is distinct from old.terms or
		new.tax_label is distinct from old.tax_label or
		new.tax_rate is distinct from old.tax_rate or
		new.subtotal is distinct from old.subtotal or
		new.tax_amount is distinct from old.tax_amount or
		new.total is distinct from old.total or
		new.valid_until is distinct from old.valid_until or
		new.document_path is distinct from old.document_path or
		new.document_hash is distinct from old.document_hash
	) then
		raise exception using errcode = '55000', message = 'Sent quote commercial data is immutable';
	end if;
	return new;
end;
$$;

