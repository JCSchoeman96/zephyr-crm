create or replace function private.record_task_activity()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
	v_event_type text;
	v_summary text;
	v_metadata jsonb;
begin
	if tg_op = 'INSERT' then
		v_event_type := case when new.fulfilment_case_id is not null and new.type = 'payment_follow_up' then 'payment_follow_up_created' else 'task_created' end;
		v_summary := case
			when new.type = 'follow_up' then 'Follow-up task created'
			when new.type = 'payment_follow_up' then 'Payment follow-up task created'
			else format('Task created: %s', new.title)
		end;
		v_metadata := jsonb_build_object('task_type', new.type, 'automation_key', new.automation_key, 'due_at', new.due_at);
	elsif old.status = 'open' and new.status = 'completed' then
		v_event_type := 'task_completed';
		v_summary := format('Task completed: %s', new.title);
		v_metadata := jsonb_build_object('task_type', new.type, 'lock_version', new.lock_version);
	elsif old.status = 'open' and new.status = 'cancelled' then
		v_event_type := 'task_cancelled';
		v_summary := format('Task cancelled: %s', new.title);
		v_metadata := jsonb_build_object('task_type', new.type, 'lock_version', new.lock_version);
	elsif old.status = 'open' and new.status = 'open' and new.due_at is distinct from old.due_at then
		v_event_type := 'task_rescheduled';
		v_summary := format('Task rescheduled: %s', new.title);
		v_metadata := jsonb_build_object('task_type', new.type, 'from_due_at', old.due_at, 'to_due_at', new.due_at, 'lock_version', new.lock_version);
	else
		return new;
	end if;
	insert into public.activities (
		lead_id, client_id, quote_id, task_id, fulfilment_case_id, actor_id,
		event_type, metadata, summary
	)
	values (
		new.lead_id, new.client_id, new.quote_id, new.id, new.fulfilment_case_id,
		auth.uid(), v_event_type, v_metadata, v_summary
	);
	return new;
end;
$$;

