create or replace function private.create_fulfilment_case_for_accepted_quote(
	p_quote_id uuid,
	p_actor uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
	v_actor uuid := coalesce(p_actor, (select auth.uid()));
	v_quote public.quotes%rowtype;
	v_lead public.leads%rowtype;
	v_case public.fulfilment_cases%rowtype;
begin
	-- Quote is the input authority, so every handoff locks Quote before Lead.
	select * into v_quote from public.quotes where id = p_quote_id for update;
	if not found then raise exception using errcode = 'P0002', message = 'Quote not found'; end if;
	select * into v_lead from public.leads where id = v_quote.lead_id for update;
	if not found then raise exception using errcode = 'P0002', message = 'Lead not found'; end if;
	select * into v_case from public.fulfilment_cases where accepted_quote_id = p_quote_id for update;
	if found then
		return jsonb_build_object(
			'fulfilment_case_id', v_case.id,
			'fulfilment_number', v_case.fulfilment_number,
			'client_id', v_case.client_id,
			'lead_id', v_case.lead_id,
			'accepted_quote_id', v_case.accepted_quote_id,
			'lock_version', v_case.lock_version,
			'idempotent', true
		);
	end if;
	if v_quote.status <> 'accepted' or v_quote.accepted_at is null or length(trim(coalesce(v_quote.acceptance_source, ''))) = 0 then
		raise exception using errcode = '22023', message = 'Only an accepted Quote can create a FulfilmentCase';
	end if;
	if v_lead.pipeline_stage <> 'WON' or v_lead.converted_client_id is null then
		raise exception using errcode = '22023', message = 'Accepted Quote requires a converted WON Lead';
	end if;
	if v_quote.client_id is distinct from v_lead.converted_client_id then
		raise exception using errcode = '23514', message = 'Accepted Quote Client does not match its Lead';
	end if;
	insert into public.fulfilment_cases (client_id, lead_id, accepted_quote_id)
	values (v_lead.converted_client_id, v_lead.id, v_quote.id)
	returning * into v_case;
	insert into public.payment_milestones (fulfilment_case_id, type)
	values (v_case.id, 'deposit'), (v_case.id, 'final_balance');
	insert into public.activities (
		lead_id, client_id, quote_id, fulfilment_case_id, actor_id,
		event_type, metadata, summary
	)
	values (
		v_lead.id,
		v_case.client_id,
		v_quote.id,
		v_case.id,
		v_actor,
		'fulfilment_created',
		jsonb_build_object('fulfilment_number', v_case.fulfilment_number, 'accepted_quote_id', v_quote.id),
		'Fulfilment case created from accepted Quote'
	);
	return jsonb_build_object(
		'fulfilment_case_id', v_case.id,
		'fulfilment_number', v_case.fulfilment_number,
		'client_id', v_case.client_id,
		'lead_id', v_case.lead_id,
		'accepted_quote_id', v_case.accepted_quote_id,
		'lock_version', v_case.lock_version,
		'idempotent', false
	);
exception when unique_violation then
	select * into v_case from public.fulfilment_cases where accepted_quote_id = p_quote_id;
	if found then
		return jsonb_build_object(
			'fulfilment_case_id', v_case.id,
			'fulfilment_number', v_case.fulfilment_number,
			'client_id', v_case.client_id,
			'lead_id', v_case.lead_id,
			'accepted_quote_id', v_case.accepted_quote_id,
			'lock_version', v_case.lock_version,
			'idempotent', true
		);
	end if;
	raise;
end;
$$;

