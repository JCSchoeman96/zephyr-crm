create table if not exists public.fulfilment_cases (
	id uuid primary key default gen_random_uuid(),
	fulfilment_number bigint generated by default as identity unique,
	client_id uuid not null references public.clients (id) on delete restrict,
	lead_id uuid not null references public.leads (id) on delete restrict,
	accepted_quote_id uuid not null references public.quotes (id) on delete restrict,
	status text not null default 'open' check (status in ('open', 'completed', 'cancelled')),
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	completed_at timestamptz,
	cancelled_at timestamptz,
	cancel_reason text,
	lock_version bigint not null default 1 check (lock_version > 0),
	constraint fulfilment_cases_lifecycle_timestamps check (
		(status = 'open' and completed_at is null and cancelled_at is null and cancel_reason is null)
		or (status = 'completed' and completed_at is not null and cancelled_at is null and cancel_reason is null)
		or (status = 'cancelled' and completed_at is null and cancelled_at is not null and length(trim(coalesce(cancel_reason, ''))) > 0)
	),
	constraint fulfilment_cases_input_bounds check (
		cancel_reason is null or char_length(cancel_reason) <= 2000
	)
);

create table if not exists public.fulfilment_steps (
	id uuid primary key default gen_random_uuid(),
	fulfilment_case_id uuid not null references public.fulfilment_cases (id) on delete cascade,
	type text not null check (type in ('installation', 'courier', 'pickup')),
	status text not null,
	scheduled_for timestamptz,
	completed_at timestamptz,
	tracking_reference text,
	notes text,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	lock_version bigint not null default 1 check (lock_version > 0),
	cancelled_at timestamptz,
	cancel_reason text,
	constraint fulfilment_steps_state_shape check (
		(type = 'installation' and status in ('awaiting_schedule', 'scheduled', 'completed', 'cancelled'))
		or (type = 'courier' and status in ('awaiting_dispatch', 'dispatched', 'delivered', 'cancelled'))
		or (type = 'pickup' and status in ('preparing', 'ready_for_collection', 'collected', 'cancelled'))
	),
	constraint fulfilment_steps_terminal_evidence check (
		(
			status in ('completed', 'delivered', 'collected')
			and completed_at is not null
			and cancelled_at is null
			and cancel_reason is null
		)
		or (
			status = 'cancelled'
			and completed_at is null
			and cancelled_at is not null
			and length(trim(coalesce(cancel_reason, ''))) > 0
		)
		or (
			status not in ('completed', 'delivered', 'collected', 'cancelled')
			and completed_at is null
			and cancelled_at is null
			and cancel_reason is null
		)
	),
	constraint fulfilment_steps_scheduled_evidence check (
		type <> 'installation'
		or status in ('awaiting_schedule', 'cancelled')
		or scheduled_for is not null
	),
	constraint fulfilment_steps_input_bounds check (
		(tracking_reference is null or char_length(tracking_reference) <= 500)
		and (notes is null or char_length(notes) <= 10000)
		and (cancel_reason is null or char_length(cancel_reason) <= 2000)
	)
);

create table if not exists public.payment_milestones (
	id uuid primary key default gen_random_uuid(),
	fulfilment_case_id uuid not null references public.fulfilment_cases (id) on delete cascade,
	type text not null check (type in ('deposit', 'final_balance')),
	status text not null default 'not_due' check (status in ('not_due', 'awaiting', 'received', 'not_required')),
	requested_at timestamptz,
	received_at timestamptz,
	received_recorded_by uuid references public.profiles (id) on delete set null,
	note text,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	lock_version bigint not null default 1 check (lock_version > 0),
	constraint payment_milestones_state_evidence check (
		(
			status = 'not_due'
			and requested_at is null
			and received_at is null
			and received_recorded_by is null
		)
		or (
			status = 'awaiting'
			and requested_at is not null
			and received_at is null
			and received_recorded_by is null
		)
		or (
			status = 'received'
			and requested_at is not null
			and received_at is not null
			and received_recorded_by is not null
		)
		or (
			status = 'not_required'
			and received_at is null
			and received_recorded_by is null
		)
	),
	constraint payment_milestones_input_bounds check (
		note is null or char_length(note) <= 2000
	)
);

