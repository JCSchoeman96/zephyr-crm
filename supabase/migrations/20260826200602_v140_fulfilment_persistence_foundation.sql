create or replace function public.complete_fulfilment(
	p_fulfilment_case_id uuid,
	p_lock_version bigint
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
	v_actor uuid := (select auth.uid());
	v_case public.fulfilment_cases%rowtype;
	v_case_lock bigint;
	v_payment_count integer;
	v_has_successful_step boolean;
	v_has_incomplete_step boolean;
	v_has_unready_payment boolean;
begin
	if v_actor is null or not (select private.has_any_role(array['owner', 'admin', 'sales']::text[])) then raise exception using errcode = '42501', message = 'CRM role required'; end if;
	select * into v_case from public.fulfilment_cases where id = p_fulfilment_case_id for update;
	if not found then raise exception using errcode = 'P0002', message = 'FulfilmentCase not found'; end if;
	if v_case.status = 'completed' then
		return jsonb_build_object('fulfilment_case_id', v_case.id, 'status', v_case.status, 'lock_version', v_case.lock_version, 'idempotent', true);
	end if;
	if v_case.status <> 'open' then raise exception using errcode = '55000', message = 'Cancelled FulfilmentCases cannot be completed'; end if;
	if v_case.lock_version is distinct from p_lock_version then raise exception using errcode = '40001', message = 'Stale FulfilmentCase lock_version'; end if;
	select count(*)::integer into v_payment_count from public.payment_milestones where fulfilment_case_id = v_case.id;
	select exists (
		select 1 from public.fulfilment_steps
		where fulfilment_case_id = v_case.id
			and status in ('completed', 'delivered', 'collected')
	) into v_has_successful_step;
	select exists (
		select 1 from public.fulfilment_steps
		where fulfilment_case_id = v_case.id
			and status not in ('completed', 'delivered', 'collected', 'cancelled')
	) into v_has_incomplete_step;
	select exists (
		select 1 from public.payment_milestones
		where fulfilment_case_id = v_case.id
			and status not in ('received', 'not_required')
	) into v_has_unready_payment;
	if not v_has_successful_step then raise exception using errcode = '55000', message = 'FulfilmentCase requires a successful non-cancelled step'; end if;
	if v_has_incomplete_step then raise exception using errcode = '55000', message = 'All non-cancelled FulfilmentSteps must be successful'; end if;
	if v_payment_count <> 2 or v_has_unready_payment then raise exception using errcode = '55000', message = 'All required PaymentMilestones must be received or not required'; end if;
	update public.fulfilment_cases
	set status = 'completed', completed_at = now(), lock_version = lock_version + 1
	where id = v_case.id and lock_version = p_lock_version
	returning lock_version into v_case_lock;
	if v_case_lock is null then raise exception using errcode = '40001', message = 'FulfilmentCase changed during completion'; end if;
	insert into public.activities (lead_id, client_id, quote_id, fulfilment_case_id, actor_id, event_type, metadata, summary)
	values (v_case.lead_id, v_case.client_id, v_case.accepted_quote_id, v_case.id, v_actor, 'fulfilment_completed', jsonb_build_object('completed_at', now()), 'Fulfilment case completed');
	return jsonb_build_object('fulfilment_case_id', v_case.id, 'status', 'completed', 'completed_at', now(), 'lock_version', v_case_lock, 'idempotent', false);
end;
$$;

create or replace function public.cancel_fulfilment(
	p_fulfilment_case_id uuid,
	p_lock_version bigint,
	p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
	v_actor uuid := (select auth.uid());
	v_case public.fulfilment_cases%rowtype;
	v_reason text := nullif(trim(coalesce(p_reason, '')), '');
	v_case_lock bigint;
begin
	if v_actor is null or not (select private.has_any_role(array['owner', 'admin']::text[])) then raise exception using errcode = '42501', message = 'Owner or admin role required'; end if;
	perform private.require_current_session_aal2();
	if v_reason is null then raise exception using errcode = '22023', message = 'Fulfilment cancellation reason is required'; end if;
	select * into v_case from public.fulfilment_cases where id = p_fulfilment_case_id for update;
	if not found then raise exception using errcode = 'P0002', message = 'FulfilmentCase not found'; end if;
	if v_case.status = 'cancelled' then
		return jsonb_build_object('fulfilment_case_id', v_case.id, 'status', v_case.status, 'lock_version', v_case.lock_version, 'idempotent', true);
	end if;
	if v_case.status <> 'open' then raise exception using errcode = '22023', message = 'Completed FulfilmentCases cannot be cancelled'; end if;
	if v_case.lock_version is distinct from p_lock_version then raise exception using errcode = '40001', message = 'Stale FulfilmentCase lock_version'; end if;
	update public.fulfilment_cases
	set status = 'cancelled', cancelled_at = now(), cancel_reason = v_reason, lock_version = lock_version + 1
	where id = v_case.id and lock_version = p_lock_version
	returning lock_version into v_case_lock;
	if v_case_lock is null then raise exception using errcode = '40001', message = 'FulfilmentCase changed during cancellation'; end if;
	insert into public.activities (lead_id, client_id, quote_id, fulfilment_case_id, actor_id, event_type, metadata, summary)
	values (v_case.lead_id, v_case.client_id, v_case.accepted_quote_id, v_case.id, v_actor, 'fulfilment_cancelled', jsonb_build_object('reason', v_reason), 'Fulfilment case cancelled');
	perform private.record_security_audit('fulfilment_cancelled', 'fulfilment_case', v_case.id::text, jsonb_build_object('reason', v_reason));
	return jsonb_build_object('fulfilment_case_id', v_case.id, 'status', 'cancelled', 'cancelled_at', now(), 'lock_version', v_case_lock);
end;
$$;

