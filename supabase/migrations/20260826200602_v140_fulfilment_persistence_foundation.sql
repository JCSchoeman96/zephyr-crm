create or replace function private.validate_task_fulfilment_lineage()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
declare
	v_case public.fulfilment_cases%rowtype;
begin
	if new.fulfilment_case_id is null then
		return new;
	end if;
	select * into v_case
	from public.fulfilment_cases
	where id = new.fulfilment_case_id;
	if not found then
		raise exception using errcode = 'P0002', message = 'FulfilmentCase not found';
	end if;
	if new.lead_id is distinct from v_case.lead_id
		or new.client_id is distinct from v_case.client_id
		or (new.quote_id is not null and new.quote_id is distinct from v_case.accepted_quote_id)
	then
		raise exception using errcode = '23514', message = 'Fulfilment Task lineage does not match its case';
	end if;
	return new;
end;
$$;

