create or replace function public.create_fulfilment_step(
	p_fulfilment_case_id uuid,
	p_type text,
	p_lock_version bigint,
	p_notes text default null,
	p_tracking_reference text default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
	v_actor uuid := (select auth.uid());
	v_case public.fulfilment_cases%rowtype;
	v_step public.fulfilment_steps%rowtype;
	v_status text;
	v_case_lock bigint;
begin
	if v_actor is null or not (select private.has_any_role(array['owner', 'admin', 'sales']::text[])) then
		raise exception using errcode = '42501', message = 'CRM role required';
	end if;
	if p_type not in ('installation', 'courier', 'pickup') then raise exception using errcode = '22023', message = 'Invalid FulfilmentStep type'; end if;
	select * into v_case from public.fulfilment_cases where id = p_fulfilment_case_id for update;
	if not found then raise exception using errcode = 'P0002', message = 'FulfilmentCase not found'; end if;
	if v_case.status <> 'open' then raise exception using errcode = '55000', message = 'Closed FulfilmentCases cannot receive steps'; end if;
	perform 1
	from public.fulfilment_steps
	where fulfilment_case_id = p_fulfilment_case_id
		and type = p_type
		and status not in ('completed', 'delivered', 'collected', 'cancelled')
	limit 1;
	if found then
		raise exception using errcode = '23505', message = 'An active FulfilmentStep of this type already exists';
	end if;
	if p_lock_version is distinct from v_case.lock_version then raise exception using errcode = '40001', message = 'Stale FulfilmentCase lock_version'; end if;
	v_status := case p_type when 'installation' then 'awaiting_schedule' when 'courier' then 'awaiting_dispatch' else 'preparing' end;
	insert into public.fulfilment_steps (fulfilment_case_id, type, status, notes, tracking_reference)
	values (
		p_fulfilment_case_id,
		p_type,
		v_status,
		nullif(trim(coalesce(p_notes, '')), ''),
		nullif(trim(coalesce(p_tracking_reference, '')), '')
	)
	returning * into v_step;
	update public.fulfilment_cases
	set lock_version = lock_version + 1
	where id = p_fulfilment_case_id and lock_version = p_lock_version
	returning lock_version into v_case_lock;
	if v_case_lock is null then raise exception using errcode = '40001', message = 'FulfilmentCase changed during step creation'; end if;
	insert into public.activities (lead_id, client_id, quote_id, fulfilment_case_id, actor_id, event_type, metadata, summary)
	values (
		v_case.lead_id,
		v_case.client_id,
		v_case.accepted_quote_id,
		v_case.id,
		v_actor,
		'fulfilment_step_created',
		jsonb_build_object('step_id', v_step.id, 'type', v_step.type, 'status', v_step.status),
		format('%s step created', initcap(v_step.type))
	);
	return jsonb_build_object('step_id', v_step.id, 'status', v_step.status, 'lock_version', v_step.lock_version, 'fulfilment_case_lock_version', v_case_lock, 'idempotent', false);
end;
$$;

create or replace function public.schedule_fulfilment_step(
	p_step_id uuid,
	p_lock_version bigint,
	p_scheduled_for timestamptz
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
	v_actor uuid := (select auth.uid());
	v_case public.fulfilment_cases%rowtype;
	v_step public.fulfilment_steps%rowtype;
	v_case_id uuid;
	v_case_lock bigint;
begin
	if v_actor is null or not (select private.has_any_role(array['owner', 'admin', 'sales']::text[])) then raise exception using errcode = '42501', message = 'CRM role required'; end if;
	if p_scheduled_for is null then raise exception using errcode = '22023', message = 'A scheduled time is required'; end if;
	select fulfilment_case_id into v_case_id from public.fulfilment_steps where id = p_step_id;
	if not found then raise exception using errcode = 'P0002', message = 'FulfilmentStep not found'; end if;
	select * into v_case from public.fulfilment_cases where id = v_case_id for update;
	select * into v_step from public.fulfilment_steps where id = p_step_id for update;
	if v_case.status <> 'open' then raise exception using errcode = '55000', message = 'Closed FulfilmentCases are read-only'; end if;
	if v_step.type <> 'installation' or v_step.status <> 'awaiting_schedule' then raise exception using errcode = '22023', message = 'Only awaiting installation steps can be scheduled'; end if;
	if v_step.lock_version is distinct from p_lock_version then raise exception using errcode = '40001', message = 'Stale FulfilmentStep lock_version'; end if;
	update public.fulfilment_steps
	set status = 'scheduled', scheduled_for = p_scheduled_for, lock_version = lock_version + 1
	where id = p_step_id and lock_version = p_lock_version
	returning * into v_step;
	update public.fulfilment_cases
	set lock_version = lock_version + 1
	where id = v_case.id
	returning lock_version into v_case_lock;
