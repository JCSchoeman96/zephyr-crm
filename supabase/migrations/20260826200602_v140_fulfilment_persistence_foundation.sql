create or replace function private.create_task_impl(
	p_fulfilment_case_id uuid,
	p_lead_id uuid,
	p_client_id uuid,
	p_quote_id uuid,
	p_type text,
	p_title text,
	p_description text,
	p_assigned_to uuid,
	p_due_at timestamptz,
	p_automation_key text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
	v_actor uuid := (select auth.uid());
	v_task public.tasks%rowtype;
	v_existing public.tasks%rowtype;
	v_quote public.quotes%rowtype;
	v_lead public.leads%rowtype;
	v_case public.fulfilment_cases%rowtype;
	v_lead_id uuid := p_lead_id;
	v_client_id uuid := p_client_id;
	v_parent_count integer;
begin
	if v_actor is null or not (select private.has_any_role(array['owner', 'admin', 'sales']::text[])) then
		raise exception using errcode = '42501', message = 'CRM role required';
	end if;
	if p_automation_key is not null then
		raise exception using errcode = '42501', message = 'Automation keys require a trusted action';
	end if;
	if length(trim(coalesce(p_title, ''))) = 0 then
		raise exception using errcode = '22023', message = 'Task title is required';
	end if;

	if p_fulfilment_case_id is not null then
		if p_type not in ('plan_fulfilment', 'schedule_installation', 'complete_installation', 'dispatch_order', 'confirm_delivery', 'prepare_pickup', 'confirm_collection', 'payment_follow_up') then
			raise exception using errcode = '22023', message = 'Invalid Fulfilment Task type';
		end if;
		select * into v_case from public.fulfilment_cases where id = p_fulfilment_case_id for update;
		if not found then raise exception using errcode = 'P0002', message = 'FulfilmentCase not found'; end if;
		if v_case.status <> 'open' then raise exception using errcode = '55000', message = 'Closed FulfilmentCases cannot receive Tasks'; end if;
		v_lead_id := v_case.lead_id;
		v_client_id := v_case.client_id;
		if p_lead_id is not null and p_lead_id is distinct from v_lead_id then raise exception using errcode = '23514', message = 'Fulfilment Task Lead does not match its case'; end if;
		if p_client_id is not null and p_client_id is distinct from v_client_id then raise exception using errcode = '23514', message = 'Fulfilment Task Client does not match its case'; end if;
		if p_quote_id is not null and p_quote_id is distinct from v_case.accepted_quote_id then raise exception using errcode = '23514', message = 'Fulfilment Task Quote does not match its case'; end if;
		if p_type = 'payment_follow_up' then
			select * into v_existing
			from public.tasks
			where fulfilment_case_id = p_fulfilment_case_id
				and type = 'payment_follow_up'
				and status = 'open'
			order by created_at, id
			limit 1
			for update;
			if found then
				return jsonb_build_object('task_id', v_existing.id, 'lock_version', v_existing.lock_version, 'idempotent', true);
			end if;
		end if;
	else
		if p_quote_id is not null then
			select * into v_quote from public.quotes where id = p_quote_id for share;
			if not found then raise exception using errcode = 'P0002', message = 'Quote not found'; end if;
			select * into v_lead from public.leads where id = v_quote.lead_id for share;
			v_lead_id := v_quote.lead_id;
			v_client_id := coalesce(v_quote.client_id, v_lead.converted_client_id);
			if p_lead_id is not null and p_lead_id <> v_lead_id then raise exception using errcode = '23514', message = 'Task Lead does not match Quote'; end if;
			if p_client_id is not null and p_client_id is distinct from v_client_id then raise exception using errcode = '23514', message = 'Task Client does not match Quote'; end if;
		else
			if p_type not in ('review_lead', 'call_client', 'prepare_quote', 'send_quote', 'follow_up', 'confirm_acceptance', 'custom') then
				raise exception using errcode = '22023', message = 'Invalid Task type';
			end if;
			v_parent_count := (p_lead_id is not null)::integer + (p_client_id is not null)::integer;
			if v_parent_count <> 1 then raise exception using errcode = '23514', message = 'A Task without a Quote requires exactly one Lead or Client'; end if;
			if p_lead_id is not null and not exists (select 1 from public.leads where id = p_lead_id) then raise exception using errcode = 'P0002', message = 'Lead not found'; end if;
			if p_client_id is not null and not exists (select 1 from public.clients where id = p_client_id) then raise exception using errcode = 'P0002', message = 'Client not found'; end if;
		end if;
	end if;

	if p_assigned_to is not null and not exists (
		select 1 from public.profiles where id = p_assigned_to and status = 'active' and role in ('owner', 'admin', 'sales')
	) then
		raise exception using errcode = '22023', message = 'Task assignee must be an active CRM user';
	end if;

	insert into public.tasks (
		lead_id, client_id, quote_id, fulfilment_case_id, type, title, description,
		assigned_to, due_at, created_by
	)
	values (
		v_lead_id,
		v_client_id,
		p_quote_id,
		p_fulfilment_case_id,
		p_type,
		trim(p_title),
		nullif(trim(coalesce(p_description, '')), ''),
		p_assigned_to,
		p_due_at,
		v_actor
	)
	returning * into v_task;
	return jsonb_build_object('task_id', v_task.id, 'lock_version', v_task.lock_version, 'idempotent', false);
exception when unique_violation then
	if p_fulfilment_case_id is not null and p_type = 'payment_follow_up' then
		select * into v_existing
		from public.tasks
		where fulfilment_case_id = p_fulfilment_case_id and type = 'payment_follow_up' and status = 'open'
		order by created_at, id
		limit 1;
		if found then return jsonb_build_object('task_id', v_existing.id, 'lock_version', v_existing.lock_version, 'idempotent', true); end if;
	end if;
	raise;
end;
$$;

